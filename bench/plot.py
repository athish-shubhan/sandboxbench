#!/usr/bin/env python3
"""results/*.json + results/pool.jsonl -> figures and results/SUMMARY.md"""
import json
import math
import os
import sys

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

d = sys.argv[1]
J = lambda n: json.load(open(os.path.join(d, n + ".json"))) if os.path.exists(os.path.join(d, n + ".json")) else None
C = {"runc": "#9aa5b1", "runc-aa": "#c9ced6", "runsc": "#2bb3a3"}
md = ["# SandboxBench results", "", "Generated by `bench/plot.py` from `results/*.json`.", ""]

env = (J("coldstart") or J("workloads") or {}).get("env", {})
if env:
    md += [f"Host: {env['cpu']}, {env['vcpus']} vCPU, {env['mem_total_gib']:.1f} GiB, kernel {env['kernel']}, KVM {'available' if env['kvm'] else 'not available'}. "
           f"{env['runc']}; runsc built from gVisor's go branch at commit ace9117e (release-20251215.0-48), flags {' '.join(env['runsc_flags'])}. "
           "Both runtimes run the same OCI bundle: a read-only bind of the host root filesystem, tmpfs /tmp, /work bind-mounted from the host, "
           "no network namespace interfaces besides lo, Docker-like capabilities and a seccomp deny list.", ""]


def pct(x):
    return f"{100*(x-1):+.0f}%"


# ---- cold start
cs = J("coldstart")
if cs:
    r = cs["result"]
    md += ["## 1. Sandbox lifecycle latency", "",
           f"{r['summary']['runc']['create_ms']['n']} interleaved repetitions per runtime (order rotated every repetition). Claim to first exec = create + start + "
           "the first `exec /bin/true` in the new sandbox; one-shot = `run /bin/true` with nothing pre-created. runc-aa is a second, identical runc "
           "configuration: its difference from runc is the noise floor.", "",
           "| runtime | create p50 | start p50 | first exec p50 | claim to first exec p50 / p99 | one-shot run p50 | teardown p50 |", "|---|---|---|---|---|---|---|"]
    for a in ["runc", "runc-aa", "runsc"]:
        s = r["summary"][a]
        md.append(f"| {a} | {s['create_ms']['p50']:.0f} ms | {s['start_ms']['p50']:.0f} ms | {s['first_exec_ms']['p50']:.0f} ms | "
                  f"{s['claim_to_first_exec_ms']['p50']:.0f} / {s['claim_to_first_exec_ms']['p99']:.0f} ms | {s['run_true_oneshot_ms']['p50']:.0f} ms | {s['teardown_ms']['p50']:.0f} ms |")
    mr = r["median_ratio"]
    md += ["", "| ratio of medians vs runc (95% bootstrap CI) | claim to first exec | one-shot run | teardown |", "|---|---|---|---|"]
    for o in ["runc-aa/runc", "runsc/runc"]:
        x = mr[o]
        md.append(f"| {o} | " + " | ".join(f"{x[k]['ratio']:.2f}x [{x[k]['ci95_lo']:.2f}, {x[k]['ci95_hi']:.2f}]" for k in ["claim_to_first_exec", "run_true_oneshot", "teardown"]) + " |")
    md.append("")

ex = J("exec")
if ex:
    r = ex["result"]
    md += ["## 2. Exec round trip into a running sandbox", "",
           "| runtime | `exec /bin/true` p50 / p99 | `exec python3 -c pass` p50 / p99 |", "|---|---|---|"]
    for a in ["runc", "runc-aa", "runsc"]:
        s = r["summary"][a]
        md.append(f"| {a} | {s['exec_true_ms']['p50']:.1f} / {s['exec_true_ms']['p99']:.1f} ms | {s['exec_python_ms']['p50']:.1f} / {s['exec_python_ms']['p99']:.1f} ms |")
    md.append("")

# ---- workloads
wl = J("workloads")
if wl:
    r = wl["result"]
    desc = {t["name"]: t["desc"] for t in r["tasks"]}
    agent = [t for t in r["summary"] if t["kind"] == "agent"]
    micro = [t for t in r["summary"] if t["kind"] == "micro"]
    n = agent[0]["by_arm"]["runc"]["n"] if agent else 0
    md += ["## 3. Agent workloads: wall-clock overhead", "",
           f"{n} repetitions per runtime, interleaved with rotated order, each in a fresh sandbox with an empty /work. Ratio = median(runsc) / median(runc), "
           "95% paired bootstrap CI. The A/A row is the same comparison between two identical runc arms: an effect inside the A/A interval is noise.", "",
           "| workload | what it does | runc median | runsc median | runsc vs runc | A/A (runc vs runc) |", "|---|---|---|---|---|---|"]
    for t in agent:
        a = t["by_arm"]
        rr, aa = t["runsc_over_runc"], t["runc_aa_over_runc"]
        md.append(f"| {t['task']} | {desc[t['task']]} | {a['runc']['p50']:.2f} s | {a['runsc']['p50']:.2f} s | **{pct(rr['ratio'])}** [{pct(rr['ci95_lo'])}, {pct(rr['ci95_hi'])}] | "
                  f"{pct(aa['ratio'])} [{pct(aa['ci95_lo'])}, {pct(aa['ci95_hi'])}] |")
    fails = {t["task"]: t["failures"] for t in r["summary"] if t["failures"]}
    if fails:
        md.append(f"\nFailed runs (excluded): {fails}")
    md += ["", "## 4. Syscall micro-benchmarks", "", "| benchmark | what it does | runc | runsc | runsc / runc |", "|---|---|---|---|---|"]
    for t in micro:
        a = t["by_arm"]
        unit = lambda v: f"{v/1e3:.1f} us" if v >= 1e3 else f"{v:.0f} ns"
        md.append(f"| {t['task']} | {desc[t['task']]} | {unit(a['runc']['p50'])} | {unit(a['runsc']['p50'])} | {t['runsc_over_runc']['ratio']:.1f}x |")
    md.append("")
    fig, ax = plt.subplots(figsize=(7, 0.55 * len(agent) + 1.2))
    ys = list(range(len(agent)))
    for i, t in enumerate(agent):
        rr, aa = t["runsc_over_runc"], t["runc_aa_over_runc"]
        ax.errorbar([100 * (rr["ratio"] - 1)], [i], xerr=[[100 * (rr["ratio"] - rr["ci95_lo"])], [100 * (rr["ci95_hi"] - rr["ratio"])]],
                    fmt="o", color=C["runsc"], capsize=3, label="runsc vs runc" if i == 0 else None)
        ax.errorbar([100 * (aa["ratio"] - 1)], [i - 0.25], xerr=[[100 * (aa["ratio"] - aa["ci95_lo"])], [100 * (aa["ci95_hi"] - aa["ratio"])]],
                    fmt="s", color=C["runc"], capsize=3, label="A/A: runc vs runc" if i == 0 else None)
    ax.axvline(0, color="#888", lw=0.8)
    ax.set_yticks(ys, [t["task"] for t in agent])
    ax.invert_yaxis()
    ax.set_xlabel("wall-clock change vs runc (%), median with 95% CI")
    ax.legend(frameon=False, fontsize=8, loc="lower right")
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    fig.savefig(os.path.join(d, "workload_overhead.png"), dpi=150)

mem = J("memory")
if mem:
    r = mem["result"]
    md += ["## 5. Memory per idle sandbox", "",
           "16 sandboxes running `sleep infinity` at once. PSS sums the proportional set size of every host process belonging to the sandboxes "
           "(the container process for runc; sentry, gofer and stub processes for runsc). MemAvailable drop also includes kernel memory, after dropping caches.", "",
           "| runtime | host processes per sandbox | PSS per sandbox | MemAvailable drop per sandbox | idle sandboxes per 64 GiB (by PSS) |", "|---|---|---|---|---|"]
    for a in ["runc", "runsc"]:
        x = r[a]
        drop = x['mem_available_drop_per_sandbox_mib']
        md.append(f"| {a} | {x['host_processes_per_sandbox']} | {x['pss_per_sandbox_mib']:.1f} MiB | {f'{drop:.1f} MiB' if drop > 1 else 'below noise (<1 MiB)'} | {x['idle_sandboxes_per_64gib_by_pss']:,.0f} |")
    md += ["", "runc is driven directly here, without containerd's per-pod shim process, so its row is only the container's own process. "
           "Idle density is an upper bound: a real agent sandbox holds a working set (an interpreter, a repo, test processes) far larger than either runtime's overhead.", ""]

iso = J("isolation")
if iso:
    r = iso["result"]
    keys = list(r["runc"].keys())
    md += ["## 6. Isolation checks (from inside the sandbox)", "",
           "Limits set on both: memory 256 MiB, pids 64, no network interfaces except lo. Each line is a separate exec, so a check that kills the sandbox "
           "cannot hide the others.", "", "| check | runc | runsc |", "|---|---|---|"]
    for k in keys:
        f = lambda v: json.dumps(v) if not isinstance(v, str) else v
        md.append(f"| {k} | {f(r['runc'].get(k))} | {f(r['runsc'].get(k))} |")
    md.append("")

# ---- snapshot / restore, pause / resume
sn = J("snapshot")
if sn:
    rows = {x["runtime"]: x for x in sn["result"]}
    md += ["## 6b. Warm state: checkpoint/restore and pause/resume", "",
           "A sandbox whose init process imports json, sqlite3, numpy, pandas and matplotlib (a data-analysis agent's first step), then writes a heartbeat "
           "every 5 ms. Cold: create + start until the imports are done. Restore (gVisor only; runc's checkpoint needs CRIU, which was not available): "
           "`runsc checkpoint` of the warm sandbox, then `runsc restore --detach` into a new container, until the heartbeat advances again.", "",
           "| | runc | runsc |", "|---|---|---|"]
    def g(rt, k, q="p50"):
        v = rows.get(rt, {}).get(k)
        return "" if not v else f"{v[q]:.0f} ms"
    md.append(f"| cold start to warm (p50) | {g('runc','cold_create_start_to_ready_ms')} | {g('runsc','cold_create_start_to_ready_ms')} |")
    md.append(f"| cold start to warm (p90) | {g('runc','cold_create_start_to_ready_ms','p90')} | {g('runsc','cold_create_start_to_ready_ms','p90')} |")
    imp = {rt: (sorted(x.get("import_sec_inside") or [0])[len(x.get("import_sec_inside") or [0]) // 2]) for rt, x in rows.items()}
    md.append(f"| of which imports, inside the sandbox (median) | {1000*imp.get('runc',0):.0f} ms | {1000*imp.get('runsc',0):.0f} ms |")
    md.append(f"| checkpoint (p50) | n/a | {g('runsc','checkpoint_ms')} |")
    if rows.get("runsc", {}).get("checkpoint_image_mib"):
        md.append(f"| checkpoint image | n/a | {rows['runsc']['checkpoint_image_mib']:.0f} MiB |")
    md.append(f"| restore to running again (p50) | n/a | {g('runsc','restore_to_running_ms')} |")
    md.append(f"| restore to running again (p90) | n/a | {g('runsc','restore_to_running_ms','p90')} |")
    md.append(f"| pause (p50) | {g('runc','pause_ms')} | {g('runsc','pause_ms')} |")
    md.append(f"| resume (p50) | {g('runc','resume_ms')} | {g('runsc','resume_ms')} |")
    errs = sum(len(x.get("errors") or []) for x in rows.values())
    md += ["", f"{rows.get('runsc', {}).get('cold_create_start_to_ready_ms', {}).get('n', 0)} repetitions per runtime; {errs} errors.", ""]

# ---- pool
pp = os.path.join(d, "pool.jsonl")
if os.path.exists(pp):
    P = [json.loads(l) for l in open(pp)]
    pols = ["static", "hpa", "hpa-nomax", "keda", "predictive", "predictive+hints"]
    col = {"static": "#9aa5b1", "hpa": "#5b8def", "hpa-nomax": "#a7c0f5", "keda": "#c75b7a", "predictive": "#2bb3a3", "predictive+hints": "#e8a33d"}
    fig, ax = plt.subplots(figsize=(7, 4.2))
    for p in pols:
        rs = sorted([r for r in P if r["policy"] == p], key=lambda r: r["idle_sandbox_hours_per_day"])
        if rs:
            ax.plot([r["idle_sandbox_hours_per_day"] for r in rs], [r["p99_ms"] for r in rs], "-o", color=col[p], label=p, ms=4)
    ax.set_xscale("symlog", linthresh=10)
    ax.set_yscale("log")
    ax.axhline(1000, color="#888", lw=0.8, ls="--")
    ax.set_xlabel("idle warm sandbox-hours per day")
    ax.set_ylabel("p99 claim-to-ready (ms)")
    ax.legend(frameon=False, fontsize=8)
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    fig.savefig(os.path.join(d, "pool_pareto.png"), dpi=150)
    md += ["## 7. Warm-pool policies (simulation)", "",
           "Discrete-event simulation of 14 days of claims; policies are scored on days 8-14 and the predictive policy learns from days 1-7. "
           "Claims: interactive agent sessions (diurnal Poisson), a nightly eval suite of 600 tasks (launch time jittered +/-10 min, 100 concurrent), "
           "PR-triggered eval suites on weekdays (80-300 tasks, 100 concurrent), and an RL job that claims 128 sandboxes at once every step (10:00-22:00). "
           "Creating a sandbox takes a lognormal scheduling delay (median 2 s) plus a runsc claim-to-first-exec sample from section 1, with at most 32 "
           "creations in flight. A claim served from the warm pool takes 50 ms. SLO: 1 s. Hints: the eval scheduler announces each suite and the RL trainer "
           "announces its next step when training starts (both up to 90 s ahead); the policy acts on them 30 s ahead.", "",
           "| policy | knob | p50 ms | p99 ms | claims over 1 s | p99 eval / RL / interactive (ms) | idle sandbox-hours/day | RL GPU stall s/day |",
           "|---|---|---|---|---|---|---|---|"]
    for p in pols:
        for r in [r for r in P if r["policy"] == p]:
            c = r["p99_ms_by_class"]
            md.append(f"| {p} | {r['knob']:g} | {r['p50_ms']:.0f} | {r['p99_ms']:.0f} | {100*r['share_over_slo']:.2f}% | "
                      f"{c.get('eval',0):.0f} / {c.get('rl',0):.0f} / {c.get('interactive',0):.0f} | {r['idle_sandbox_hours_per_day']:.1f} | {r['rl_gpu_stall_sec_per_day']:.0f} |")
    md.append("")
    for target in [1000, 500]:
        best = {}
        for p in pols:
            ok = [r for r in P if r["policy"] == p and r["p99_ms"] <= target]
            if ok:
                best[p] = min(ok, key=lambda r: r["idle_sandbox_hours_per_day"])
        if best:
            md += [f"Cheapest configuration per policy with p99 claim latency at or under {target} ms:", "",
                   "| policy | knob | p99 ms | idle sandbox-hours/day | RL stall s/day |", "|---|---|---|---|---|"]
            for p, r in best.items():
                md.append(f"| {p} | {r['knob']:g} | {r['p99_ms']:.0f} | {r['idle_sandbox_hours_per_day']:.1f} | {r['rl_gpu_stall_sec_per_day']:.0f} |")
            md.append("")

open(os.path.join(d, "SUMMARY.md"), "w").write("\n".join(md) + "\n")
print("\n".join(md))
